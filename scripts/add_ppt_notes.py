def main():
    root = Path(r"e:\a_myprofile\zudao")
    ppt_path = next(root.glob("*.pptx"))
    backup_path = ppt_path.with_name(f"{ppt_path.stem}_before_notes{ppt_path.suffix}")

    if not backup_path.exists():
        copy2(ppt_path, backup_path)

    prs = Presentation(str(ppt_path))
    if len(prs.slides) != len(NOTES):
        raise ValueError(f"Expected {len(NOTES)} slides, found {len(prs.slides)}")

    for idx, slide in enumerate(prs.slides, start=1):
        notes_slide = slide.notes_slide
        text_frame = notes_slide.notes_text_frame
        text_frame.clear()

        paragraphs = NOTES[idx].split("\n")
        text_frame.text = paragraphs[0]
        for paragraph in paragraphs[1:]:
            text_frame.add_paragraph().text = paragraph

    prs.save(str(ppt_path))
    print(f"Updated notes for {len(prs.slides)} slides: {ppt_path}")
    print(f"Backup created at: {backup_path}")


if __name__ == "__main__":
    main()
